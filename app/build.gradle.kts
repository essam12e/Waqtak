// Optional release signing: provided only through environment variables or an
// untracked keystore.properties file. No secrets are stored in the repository.
val signingProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
fun signingValue(key: String): String? = System.getenv(key) ?: signingProps.getProperty(key)

